// R3.3 (D-300): the fitted shape table and term-structure constant as the contract's and the client's source, from
// one place. `codegen.mjs` writes them; the `tail-table-sync` invariant renders them again and compares.
import { readFileSync } from "node:fs";
import { join } from "node:path";

export const TABLE_JSON = "scripts/calibrate/table.json";
export const SOL_OUT = "contracts/src/markets/TailTableData.sol";
export const TS_OUT = "packages/core/src/market/tail-table.ts";

const P_ONE = 1_000_000;
const WAD = 1_000_000_000_000_000_000n;
const Z_SCALE_E4 = 10_000;
const ENTRY_BYTES = 3;
const TAU_BYTES = 2;
const U16_BYTES = 2;
const U64_BYTES = 8;
/** `MarketTypes` TAIL_FORMAT: the blob's layout version. */
const FORMAT = 1;
const HEX_RADIX = 16;
const HEX_PER_BYTE = 2;
const WAD_DIGITS = 18;

const hex = (value, bytes) => value.toString(HEX_RADIX).padStart(bytes * HEX_PER_BYTE, "0");

/** The table as integers, checked: every row starts at ½, never falls and never passes 1. */
export function tableOf(json) {
  const cdf = json.cdf.map((row) => row.map((x) => Math.round(x * P_ONE)));
  for (const [r, row] of cdf.entries()) {
    if (row[0] !== P_ONE / 2) throw new Error(`row ${r} must start at 500000`);
    for (let i = 1; i < row.length; i++) {
      if (row[i] < row[i - 1] || row[i] > P_ONE) throw new Error(`row ${r} not a CDF at ${i}`);
    }
  }
  const zStepE4 = Math.round(json.zStep * Z_SCALE_E4);
  return {
    taus: json.taus,
    zStepE4,
    points: cdf[0].length,
    cdf,
    weightWad: toWad(json.markWeight),
    fadeWad: toWad(json.kappaPerSec),
    scale: json.longRunScale,
  };
}

/** A decimal × 1e18, from its shortest round-trip digits (0.6 → 6e17 exactly; no float noise past what the JSON says). */
function toWad(x) {
  const text = String(x).includes("e") ? x.toFixed(WAD_DIGITS) : String(x);
  const [whole, frac = ""] = text.split(".");
  return BigInt(whole) * WAD + BigInt(frac.padEnd(WAD_DIGITS, "0").slice(0, WAD_DIGITS));
}

export function readTable(root) {
  return tableOf(JSON.parse(readFileSync(join(root, TABLE_JSON), "utf8")));
}

/** The table as the bytes its data contract holds (`MarketTypes` TAIL_*: a 22-byte header, the horizons, the rows). */
export function blobOf(t) {
  return [
    hex(FORMAT, 1),
    hex(t.taus.length, 1),
    hex(t.points, U16_BYTES),
    hex(t.zStepE4, U16_BYTES),
    hex(t.weightWad, U64_BYTES),
    hex(t.fadeWad, U64_BYTES),
    ...t.taus.map((x) => hex(x, TAU_BYTES)),
    ...t.cdf.flat().map((x) => hex(x, ENTRY_BYTES)),
  ].join("");
}

