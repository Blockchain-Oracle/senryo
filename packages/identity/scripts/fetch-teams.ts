/**
 * Every event team's crest and colours (D-315, F11), fetched from ESPN's public team feeds — the same source the
 * committee's first member reads (`services/keeper/src/events/sources/espn.ts`), so a feed's abbreviation always finds
 * its crest. Per league in `@senryo/config` `LEAGUES`: `site.api.espn.com/apis/site/v2/sports/{espn}/teams` lists each
 * team's abbreviation, name, `color`/`alternateColor` and its logos (the default and the `dark` one). Each crest is
 * downsized to 128 px (2× a 48 px crest, research 10 §5), written once to `assets/teams/{league}/{ABBR}[-dark].png`,
 * pinned by sha256, and listed in `src/generated/teams.ts` (names, colours, hashes) with the require and import maps
 * the apps draw from. Self-hosted, never hot-linked. The leagues reserve their marks; the owner chose them (D-315).
 *   pnpm --filter @senryo/identity run fetch:teams
 */
import { createHash } from "node:crypto";
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { LEAGUES } from "@senryo/config";
import sharp from "sharp";

const BASE = "https://site.api.espn.com/apis/site/v2/sports";
const SIZE = 128;
const HEX = "hex";
const pkg = join(dirname(fileURLToPath(import.meta.url)), "..");
const assets = join(pkg, "assets", "teams");

interface EspnLogo {
  href: string;
  rel?: string[];
}
interface EspnTeam {
  abbreviation: string;
  displayName: string;
  color?: string;
  alternateColor?: string;
  logos?: EspnLogo[];
}

async function json<T>(url: string): Promise<T> {
  const res = await fetch(url, { headers: { accept: "application/json" } });
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return (await res.json()) as T;
}

async function crest(url: string, file: string): Promise<string> {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  const png = await sharp(Buffer.from(await res.arrayBuffer()))
    .resize(SIZE, SIZE, { fit: "contain", background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .png({ compressionLevel: 9, palette: true })
    .toBuffer();
  writeFileSync(file, png);
  return createHash("sha256").update(png).digest(HEX);
}

const hex = (v: string | undefined) => (v && /^[0-9a-f]{6}$/i.test(v) ? `#${v.toUpperCase()}` : null);

interface Row {
  id: string;
  league: string;
  abbr: string;
  name: string;
  color: string | null;
  alt: string | null;
  light: string;
  dark: string | null;
  sha256: string;
}

rmSync(assets, { recursive: true, force: true });
const rows: Row[] = [];
for (const league of LEAGUES) {
  const dir = join(assets, league.key);
  mkdirSync(dir, { recursive: true });
  const feed = await json<{ sports: { leagues: { teams: { team: EspnTeam }[] }[] }[] }>(`${BASE}/${league.espn}/teams`);
  const teams = feed.sports[0]?.leagues[0]?.teams ?? [];
  for (const { team } of teams) {
    const abbr = team.abbreviation.toUpperCase();
    const logos = team.logos ?? [];
    const light = logos.find((l) => !l.rel?.includes("dark")) ?? logos[0];
    const dark = logos.find((l) => l.rel?.includes("dark"));
    if (!light) continue;
    const sha = await crest(light.href, join(dir, `${abbr}.png`));
    const darkSha = dark ? await crest(dark.href, join(dir, `${abbr}-dark.png`)) : null;
    rows.push({
      id: `team:${league.key}:${abbr}`,
      league: league.key,
      abbr,
      name: team.displayName,
      color: hex(team.color),
      alt: hex(team.alternateColor),
      light: `${league.key}/${abbr}.png`,
      dark: darkSha ? `${league.key}/${abbr}-dark.png` : null,
      sha256: sha,
    });
  }
  console.log(`${league.name}: ${teams.length} teams`);
}
rows.sort((a, b) => a.id.localeCompare(b.id));

const header =
  "/** Generated by packages/identity/scripts/fetch-teams.ts from ESPN's team feeds (D-315). Do not edit. */";
const table = [
  header,
  "",
  "export interface TeamCrest {",
  "  name: string;",
  "  /** The team's colours (ESPN `color` / `alternateColor`), for a card's edge bands and wash. */",
  "  color: string | null;",
  "  alt: string | null;",
  "  /** Whether a crest drawn for dark grounds exists. */",
  "  dark: boolean;",
  "  sha256: string;",
  "}",
  "",
  "export const TEAM_CRESTS: Readonly<Record<string, TeamCrest>> = {",
  ...rows.map(
    (r) =>
      `  "${r.id}": { name: ${JSON.stringify(r.name)}, color: ${JSON.stringify(r.color)}, alt: ${JSON.stringify(r.alt)}, dark: ${r.dark !== null}, sha256: "${r.sha256}" },`,
  ),
  "};",
  "",
].join("\n");
writeFileSync(join(pkg, "src", "generated", "teams.ts"), table);

const key = (r: Row, dark: boolean) => `"${r.id}${dark ? ":dark" : ""}"`;
const native = [
  header,
  "",
  "/** `team:{league}:{ABBR}` (and `…:dark`) → the bundled crest (Metro's asset id). */",
  "export const TEAM_CREST_SOURCES: Readonly<Record<string, number>> = {",
  ...rows.flatMap((r) => [
    `  ${key(r, false)}: require("../../../assets/teams/${r.light}"),`,
    ...(r.dark ? [`  ${key(r, true)}: require("../../../assets/teams/${r.dark}"),`] : []),
  ]),
  "};",
  "",
].join("\n");
writeFileSync(join(pkg, "src", "generated", "native", "team-crests.ts"), native);

const vars = new Map<string, string>();
const web = [
  header,
  ...rows.flatMap((r, i) => {
    vars.set(`${r.id}`, `c${i}`);
    const lines = [`import c${i} from "../../../assets/teams/${r.light}";`];
    if (r.dark) {
      vars.set(`${r.id}:dark`, `d${i}`);
      lines.push(`import d${i} from "../../../assets/teams/${r.dark}";`);
    }
    return lines;
  }),
  "",
  "/** Next's static import is StaticImageData; a plain bundler gives the URL itself. */",
  'const url = (x: string | { src: string }) => (typeof x === "string" ? x : x.src);',
  "",
  "/** `team:{league}:{ABBR}` (and `…:dark`) → the crest's URL (a static import: hashed and cached by the build). */",
  "export const TEAM_CREST_URLS: Readonly<Record<string, string>> = {",
  ...[...vars.entries()].map(([k, v]) => `  "${k}": url(${v}),`),
  "};",
  "",
].join("\n");
writeFileSync(join(pkg, "src", "generated", "web", "team-crests.ts"), web);
console.log(`${rows.length} crests (${rows.filter((r) => r.dark).length} with a dark crest) → assets/teams`);
