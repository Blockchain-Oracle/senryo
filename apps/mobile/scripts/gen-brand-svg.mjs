/**
 * Writes `src/theme/brand-svg.ts`: the brand lockup's SVG markup as a string, for drawing with Skia where a React
 * component can't go (the replay video's brand band, Q3 / D-350). The source of truth stays `brand/senryo-lockup.svg`;
 * run `node apps/mobile/scripts/gen-brand-svg.mjs` after it changes.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../..");
const svg = readFileSync(resolve(root, "brand/senryo-lockup.svg"), "utf8").trim();
const out = [
  "// Generated by apps/mobile/scripts/gen-brand-svg.mjs from brand/senryo-lockup.svg — do not edit by hand.",
  "",
  "/** The Senryo lockup (seal and wordmark) as SVG markup, for Skia (`Skia.SVG.MakeFromString`). */",
  // Biome's shape for a long string: the value on its own line.
  "export const LOCKUP_SVG =",
  // Single quotes (the markup is full of double ones), newlines escaped — as Biome writes it.
  `  '${svg.replace(/\\/g, "\\\\").replace(/'/g, "\\'").replace(/\n/g, "\\n")}';`,
  "",
].join("\n");
writeFileSync(resolve(here, "../src/theme/brand-svg.ts"), out);
console.log("wrote src/theme/brand-svg.ts");
