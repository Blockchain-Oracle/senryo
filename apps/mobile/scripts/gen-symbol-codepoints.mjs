/**
 * Generates `src/components/kit/symbol-codepoints.ts`: the Material Symbols codepoint of every Android glyph name used
 * in `symbols.tsx`, read from the map expo-symbols ships (`build/android/symbols.json`). Only the names we use ship —
 * not the 4,000-entry map. Run after adding a glyph: `node apps/mobile/scripts/gen-symbol-codepoints.mjs`.
 */
import { readFileSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const app = join(dirname(fileURLToPath(import.meta.url)), "..");
const pkg = realpathSync(join(app, "node_modules/expo-symbols"));
const map = JSON.parse(readFileSync(join(pkg, "build/android/symbols.json"), "utf8"));
const source = readFileSync(join(app, "src/components/kit/symbols.tsx"), "utf8");
const names = [...new Set([...source.matchAll(/android: "([a-z0-9_]+)"/g)].map((m) => m[1]))].sort();
const missing = names.filter((n) => map[n] === undefined);
if (missing.length > 0) {
  console.error(`Unknown Material Symbols: ${missing.join(", ")}`);
  process.exit(1);
}
const lines = names.map((n) => `  ${n}: 0x${map[n].toString(16)},`).join("\n");
const out = `/** Generated by apps/mobile/scripts/gen-symbol-codepoints.mjs from expo-symbols' Material Symbols map. Do not edit. */
export const ANDROID_CODEPOINTS = {
${lines}
} as const;

export type AndroidSymbolName = keyof typeof ANDROID_CODEPOINTS;
`;
writeFileSync(join(app, "src/components/kit/symbol-codepoints.ts"), out);
console.log(`${names.length} glyphs`);
